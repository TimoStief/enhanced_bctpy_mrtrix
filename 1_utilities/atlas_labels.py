# ── Detection ──────────────────────────────────────────────────────────────

def detect_atlas(data_dir: "Path | str", sample_filenames: list[str] | None = None) -> str:
    """Auto-detect atlas from folder path or filenames. Returns atlas key."""
    search = str(data_dir).lower()
    if sample_filenames:
        search += " " + " ".join(f.lower() for f in sample_filenames[:10])

    # Order: more specific first
    priority = [
        "Brainnectome", "HCPex", "HCP-MMP", "JulichBrain",
        "FreeSurferDKT_Cortical", "FreeSurferDKT_Subcortical", "FreeSurferDKT_Tissue",
        "FreeSurferSeg", "CerebrA", "Cerebellum-SUIT", "ATAG_basal_ganglia",
        "BrainSeg", "CHA", "Campbell", "THOMAS", "Kleist", "Brodmann", "AAL",
    ]
    for key in priority:
        if key not in ATLAS_DB:
            continue
        for kw in ATLAS_DB[key]["keywords"]:
            if kw in search:
                return key
    return "unknown"


def get_label(atlas_key: str, node_id: int) -> str:
    """Return anatomical label for a node. Falls back to Node_{id}."""
    # Case-insensitive lookup
    key = atlas_key
    if key not in ATLAS_DB:
        key = atlas_key.capitalize()
    if key not in ATLAS_DB:
        key = next((k for k in ATLAS_DB if k.lower() == atlas_key.lower()), None)
    if not key:
        return f"Node_{node_id}"
    labels = ATLAS_DB[key].get("labels", {})
    return labels.get(str(node_id), f"Node_{node_id}")


def get_all_labels(atlas_key: str) -> dict[int, str]:
    """Return full {node_id: label} dict."""
    if atlas_key not in ATLAS_DB:
        return {}
    return {int(k): v for k, v in ATLAS_DB[atlas_key].get("labels", {}).items()}


def atlas_summary() -> str:
    lines = [f"  {'Atlas':<30} {'Nodes':<8} {'Labels':<8} Source"]
    lines.append("  " + "-" * 70)
    for key, d in ATLAS_DB.items():
        n = str(d["n_nodes"])
        nl = str(len(d["labels"]))
        lines.append(f"  {key:<30} {n:<8} {nl:<8} {d['source']}")
    return "\n".join(lines)


